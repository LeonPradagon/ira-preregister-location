interface I18nContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey, values?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export const I18nProvider: React.FC<{ children: React.ReactNode; defaultLanguage?: Language }> = ({
  children,
  defaultLanguage,
}) => {
  const [language, setLanguageState] = useState<Language>(() => {
    if (defaultLanguage) return defaultLanguage;
    const saved = localStorage.getItem('el_language');
    return saved === 'en' || saved === 'id' ? saved : 'en';
  });
  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);
  const setLanguage = (next: Language) => {
    setLanguageState(next);
    localStorage.setItem('el_language', next);
    document.documentElement.lang = next;
  };
  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      setLanguage,
      t: (key, values) => {
        const template =
          deliveryWording[language][key] ??
          customerMessages[language][key] ??
          userFriendlyMessages[language][key] ??
          messages[language][key] ??
          extraMessages[language][key] ??
          key;
        return Object.entries(values ?? {}).reduce(
          (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
          template,
        );
      },
    }),
    [language],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useTranslation = () => {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useTranslation must be used within I18nProvider');
  return context;
};
